const POOL = RAW.split('\n').map((line) => {
  const [c, p] = line.trim().split(/\s+/);
  return { c, p };
}).filter((x) => x.c && x.p);

/** 随机拼一句：多为 2–3 字，偶尔 4–6 字；同一句里不重复用同一个字 */
export function randomPhrase() {
  const n = chance(58) ? rndInt(2, 3) : rndInt(4, 6);
  const used = new Set();
  const chars = [];
  const pinyins = [];
  let guard = 0;
  while (chars.length < n && guard++ < n * 30) {
    const { c, p } = pick(POOL);
    if (used.has(c)) continue;
    used.add(c);
    chars.push(c);
    pinyins.push(p);
  }
  return { text: chars.join(''), pinyin: pinyins.join(' ') };
}

